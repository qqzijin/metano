MARKER_START = '<!-- LEARNED-PREFS-START -->'
MARKER_END = '<!-- LEARNED-PREFS-END -->'

def _sanitize_markers(text: str) -> str:
    """Remove evolution marker strings from content to prevent marker injection.

    S5：LLM 生成的提案内容可能伪造结束标记（MARKER_END），注入前必须先移除，
    防止逃逸出受控的 CLAUDE.md 区间写入任意内容。
    """
    return text.replace(MARKER_START, '').replace(MARKER_END, '')

def _ensure_dirs():
    EVOLUTION_DIR.mkdir(parents=True, exist_ok=True)

def _log(action: str, details: dict):
    """Append to evolution audit log."""
    _ensure_dirs()
    entry = {'timestamp': time.time(), 'action': action, **details}
    with open(LOG_FILE, 'a') as f:
        f.write(json.dumps(entry, ensure_ascii=False) + '\n')

def beliefs_to_claude_md_injection(beliefs: list[dict]) -> str:
    """Generate the marked section content for CLAUDE.md from beliefs and agent_rules."""
    from .evo_models import get_rules as get_agent_rules
    lines = [MARKER_START, '# Learned Preferences (auto-generated by evolution)']
    by_category: dict[str, list[dict]] = {}
    for b in beliefs:
        cat = b.get('category', 'general')
        by_category.setdefault(cat, []).append(b)
    for cat, cat_beliefs in sorted(by_category.items()):
        lines.append(f'\n## {cat.title()}')
        for b in cat_beliefs:
            stage = belief_stage(b)
            # S5：清除信念内容中的标记字符串，防止伪造结束标记破坏 CLAUDE.md 结构
            safe_content = _sanitize_markers(b['content'])
            lines.append(f"- {safe_content} (confidence: {b['confidence']:.0%}, stage: {stage})")
    rules = get_agent_rules(active_only=True)
    if rules:
        lines.append('\n## Behavior Rules')
        for r in rules:
            eff = r.get('effectiveness', 0)
            applied = r.get('times_applied', 0)
            eff_str = f' (effectiveness: {eff:.0%}, applied: {applied}x)' if applied > 0 else ''
            safe_rule = _sanitize_markers(r['content'])
            lines.append(f"- {safe_rule}{eff_str}")
    lines.append(MARKER_END)
    return '\n'.join(lines)

def apply_beliefs_to_claude_md(dry_run: bool=True) -> dict:
    """Inject learned beliefs into CLAUDE.md within marked section.

    Only includes beliefs with confidence >= 0.7 and not contradicted.
    Preserves all content outside the markers.
    """
    conn = get_honcho_db()
    try:
        beliefs = get_beliefs(conn, 'default')
        eligible = [b for b in beliefs if b['confidence'] >= 0.7 and (not b.get('contradicted'))]
        if not eligible:
            return {'action': 'claude_md', 'status': 'skipped', 'reason': 'no eligible beliefs (confidence >= 0.7)'}
        injection = beliefs_to_claude_md_injection(eligible)
        if dry_run:
            return {'action': 'claude_md', 'status': 'dry_run', 'injection_preview': injection[:500], 'belief_count': len(eligible)}
        content = CLAUDE_MD.read_text() if CLAUDE_MD.exists() else ''
        if MARKER_START in content:
            start_idx = content.index(MARKER_START)
            end_idx = content.index(MARKER_END) + len(MARKER_END)
            new_content = content[:start_idx] + injection + content[end_idx:]
        else:
            new_content = content.rstrip() + '\n\n' + injection + '\n'
        CLAUDE_MD.write_text(new_content)
        _log('claude_md_inject', {'belief_count': len(eligible), 'categories': list(set((b['category'] for b in eligible)))})
        return {'action': 'claude_md', 'status': 'applied', 'belief_count': len(eligible)}
    finally:
        conn.close()

def beliefs_to_memory_file(beliefs: list[dict], category: str, dry_run: bool = True) -> dict | None:
    """Generate memory files from learned beliefs.

    Creates structured memory files in the memory directory for each category
    of learned beliefs. Only includes beliefs with confidence >= 0.6.

    S6：category 来自 LLM，必须按白名单正则 [a-z0-9_-]+ 消毒，非法则拒绝，
    防止 ``learned-../xxx`` 路径穿越写任意文件。
    S1：dry_run=True 时只返回预览，不真实写入记忆文件（自动 cron 不允许直接写盘，
    用户显式运行时才真实写入）。
    """
    if category == 'behavior_pattern':
        return None
    # S6：category 白名单消毒，非法字符直接拒绝（防止路径穿越）
    if not re.fullmatch(r'[a-z0-9_-]+', category or ''):
        logger.warning(f"memory_file: 非法 category {category!r}，已拒绝写入")
        return None
    eligible = [b for b in beliefs if b['category'] == category and b['confidence'] >= 0.6 and (not b.get('contradicted'))]
    if len(eligible) < 2:
        return None
    slug = f'learned-{category}'
    filepath = MEMORY_DIR / f'{slug}.md'
    lines = ['---', f'name: {slug}', f'description: Auto-generated from learned {category} beliefs', 'metadata:', '  type: feedback', '---', '']
    for b in eligible:
        stage = belief_stage(b)
        lines.append(f"- {_sanitize_markers(b['content'])} (confidence: {b['confidence']:.0%}, stage: {stage})")
    if dry_run:
        return {'action': 'memory_file', 'category': category, 'status': 'dry_run', 'file': str(filepath), 'belief_count': len(eligible)}
    filepath.write_text('\n'.join(lines))
    _add_to_memory_index(slug, f'Auto-learned {category} preferences')
    _log('memory_file_create', {'category': category, 'belief_count': len(eligible), 'file': str(filepath)})
    return {'action': 'memory_file', 'category': category, 'file': str(filepath), 'belief_count': len(eligible)}

def _add_to_memory_index(slug: str, description: str):
    """Add a pointer to the memory index file."""
    if not MEMORY_INDEX.exists():
        return
    content = MEMORY_INDEX.read_text()
    link = f'- [{slug}]({slug}.md)'
    if link in content:
        return
    MEMORY_INDEX.write_text(content.rstrip() + f'\n{link} — {description}\n')

def beliefs_to_behavior_improvements(beliefs: list[dict]) -> list[dict]:
    """Get behavior rules from evo_models (separate from Honcho user beliefs)."""
    agent_rules = get_agent_rules(kind='behavior')
    suggestions = []
    for r in agent_rules:
        # Skip low-confidence rules so they don't clutter the proposal queue.
        if r.get('confidence', 0.5) < 0.7:
            continue
        content = r['content']
        slug = content[:30].replace(' ', '-').replace('，', '').replace('。', '').replace('、', '')
        import re
        slug = re.sub('[^\\w-]', '', slug).lower()[:30]
        suggestions.append({'id': f"evo-{r['id']}", 'rule_id': r['id'], 'type': 'behavior_improvement', 'content': content, 'suggestion': content, 'slug': slug, 'effectiveness': r['effectiveness'], 'status': 'pending' if r.get('source') == 'correction_cluster' else 'applied', 'created_at': r['created_at']})
    return suggestions

