def apply_proposal(proposal_id: int) -> dict:
    """Execute an approved proposal. Only runs if status is 'approved'.

    Dispatches to type-specific handlers. Updates proposal status to
    'applied' or 'failed' based on outcome.
    """
    from .evo_models import get_proposals, update_proposal_status
    proposals = get_proposals()
    target = next((p for p in proposals if p['id'] == proposal_id), None)
    if not target:
        return {'status': 'not_found'}
    if target['status'] != 'approved':
        return {'status': 'wrong_state', 'current_status': target['status']}

    ptype = target['proposal_type']
    content = target['content']
    detail = target.get('detail', '')

    # Record baseline metrics before applying
    try:
        from .evolution_eval import record_baseline
        record_baseline(proposal_id)
    except Exception:
        logger.exception()

    try:
        if ptype == 'behavior_improvement':
            result = _apply_behavior_improvement(content, detail)
        elif ptype == 'config_change':
            result = _apply_config_change(content, detail)
        elif ptype == 'rule_add':
            result = _apply_rule_add(content, detail)
        elif ptype == 'claude_md_inject':
            result = _apply_claude_md(content, detail)
        elif ptype == 'skill_improvement':
            result = _apply_skill_improvement(content, detail)
        elif ptype == 'new_skill_suggestion':
            result = _apply_new_skill(content, detail)
        else:
            result = {'status': 'unknown_type', 'type': ptype}

        outcome = result.get('status', 'failed')
        update_proposal_status(proposal_id, outcome if outcome in ('applied', 'failed') else 'applied',
                               json.dumps(result, ensure_ascii=False))
        _log('proposal_apply', {'proposal_id': proposal_id, 'type': ptype, 'outcome': outcome})
        return result
    except Exception:
        logger.exception()
        update_proposal_status(proposal_id, 'failed', 'execution error')
        return {'status': 'failed', 'type': ptype}


