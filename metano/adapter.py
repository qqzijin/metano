def beliefs_to_setting_suggestions(beliefs: list[dict]) -> list[dict]:
    """Generate setting change suggestions from beliefs. Never auto-applied.

    Only creates proposals with concrete, actionable key=value changes.
    Vague preferences are skipped — they belong in CLAUDE.md/memory, not config.
    """
    suggestions = []
    for b in beliefs:
        if b['confidence'] < 0.8 or b.get('contradicted'):
            continue
        cat = b.get('category', '')
        content = b.get('content', '')
        if cat != 'preference':
            continue
        # Only create proposals for preferences that map to specific config keys
        lower = content.lower()
        if '中文' in lower or 'chinese' in lower or 'language=zh' in lower:
            suggestions.append({
                'id': f"sug-{b['id']}",
                'belief_id': b['id'],
                'type': 'setting_suggestion',
                'content': 'ui_language=zh-CN',
                'suggestion': 'Set UI language to Chinese (zh-CN)',
                'status': 'pending',
                'created_at': time.time(),
            })
        elif 'proxy' in lower or '代理' in lower:
            suggestions.append({
                'id': f"sug-proxy-{b['id']}",
                'belief_id': b['id'],
                'type': 'setting_suggestion',
                'content': 'proxy_enabled=true',
                'suggestion': 'Enable proxy configuration',
                'status': 'pending',
                'created_at': time.time(),
            })
    return suggestions

def save_suggestions(suggestions: list[dict]):
    """Save suggestions to evo.db proposals table (dedup by content)."""
    from .evo_models import add_proposal, get_proposals as _get_all
    existing_contents = {p['content'] for p in _get_all()}
    for s in suggestions:
        content = s.get('suggestion', s.get('content', ''))
        if content in existing_contents:
            continue
        ptype = s.get('type', 'behavior_improvement')
        if ptype == 'setting_suggestion':
            ptype = 'config_change'
        elif ptype == 'belief_promotion':
            ptype = 'rule_add'
        detail = s.get('content', '')
        source = s.get('type', 'evolution')
        add_proposal(ptype, content, detail=detail, source=source)
        existing_contents.add(content)

def execute_adaptation_cycle(dry_run: bool=True) -> dict:
    """Run the full belief-to-action adaptation cycle.

    Generates proposals from beliefs, behavior rules, and strategy patterns.
    Proposals are stored in evo.db proposals table and pending_suggestions.json.
    """
    conn = get_honcho_db()
    try:
        beliefs = get_beliefs(conn, 'default')
        active = [b for b in beliefs if not b.get('contradicted')]
        results = {'dry_run': dry_run, 'actions': [], 'proposals_created': 0}

        # 1. Inject beliefs into CLAUDE.md
        claude_md_result = apply_beliefs_to_claude_md(dry_run=dry_run)
        results['actions'].append(claude_md_result)

        # 2. Generate memory files from beliefs
        categories = set((b['category'] for b in active))
        for cat in categories:
            mem_result = beliefs_to_memory_file(active, cat, dry_run=dry_run)
            if mem_result:
                results['actions'].append(mem_result)

        # 3. Create proposals from setting suggestions
        from .evo_models import get_proposals as _get_proposals
        all_proposals = _get_proposals()
        existing_contents = {p['content'] for p in all_proposals}
        suggestions = beliefs_to_setting_suggestions(active)
        if suggestions and not dry_run:
            for s in suggestions:
                content = s.get('suggestion', s.get('content', ''))
                if content in existing_contents:
                    continue
                pid = add_proposal('config_change', content, s.get('content', ''), source='belief')
                if not pid:
                    continue
                existing_contents.add(content)
                results['proposals_created'] += 1
            results['actions'].append({'action': 'setting_suggestions', 'count': len(suggestions), 'status': 'pending_approval'})

        # 4. Create proposals from behavior improvements
        behavior_suggestions = beliefs_to_behavior_improvements(active)
        if behavior_suggestions and not dry_run:
            for s in behavior_suggestions:
                content = s.get('content', '')
                if content in existing_contents:
                    continue
                pid = add_proposal('behavior_improvement', content, source='behavior_rule')
                if not pid:
                    continue
                existing_contents.add(content)
                results['proposals_created'] += 1
            results['actions'].append({'action': 'behavior_improvements', 'count': len(behavior_suggestions), 'status': 'pending_approval'})

        # 5. Create proposals from strategy patterns
        try:
            from .strategy import detect_strategy_patterns
            strategy_patterns = detect_strategy_patterns()
            if strategy_patterns and not dry_run:
                for p in strategy_patterns:
                    if p.get('rule_suggestion') and p.get('confidence', 0) >= 0.8:
                        ptype = _classify_strategy(p)
                        pid = add_proposal(ptype, p.get('rule_suggestion', ''), json.dumps(p, ensure_ascii=False), source='strategy')
                        if not pid:
                            continue
                        results['proposals_created'] += 1
                results['actions'].append({'action': 'strategy_patterns', 'count': len(strategy_patterns), 'status': 'pending_approval'})
        except Exception:
            logger.exception("adaptation: strategy pattern detection failed")

        _log('adaptation_cycle', {'dry_run': dry_run, 'action_count': len(results['actions']), 'proposals_created': results['proposals_created']})

        # Notify user about pending proposals
        if results['proposals_created'] > 0:
            try:
                from .evolution_notify import notify_pending_proposals
                from .evo_models import get_proposals
                pending = get_proposals(status='pending')
                notify_pending_proposals(pending)
            except Exception:
                logger.exception("adaptation: notify failed")

        return results
    finally:
        conn.close()


def _classify_strategy(pattern: dict) -> str:
    """Classify a strategy pattern into a proposal type."""
    text = f"{pattern.get('rule_suggestion', '')} {pattern.get('action_type', '')}".lower()
    if any(kw in text for kw in ['config', 'parameter', 'threshold', 'timeout']):
        return 'config_change'
    if any(kw in text for kw in ['claude.md', 'claude_md', 'instruction']):
        return 'claude_md_inject'
    if any(kw in text for kw in ['rule', 'policy', 'constraint', 'block', 'deny']):
        return 'rule_add'
    return 'behavior_improvement'


